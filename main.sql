);


-- ============================================================================
-- 1. CREATE HELPER FUNCTION TO BREAK RECURSION
-- ============================================================================

-- Function to safely fetch current user's family_id without triggering RLS loops
CREATE OR REPLACE FUNCTION public.get_auth_family_id()
RETURNS UUID 
LANGUAGE sql 
SECURITY DEFINER 
STABLE
AS $$
    SELECT family_id FROM public.profiles WHERE id = auth.uid() LIMIT 1;
$$;


