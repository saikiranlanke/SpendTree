DROP POLICY IF EXISTS "Family members can view each other profiles" ON public.profiles;
DROP POLICY IF EXISTS "Family members can view profiles" ON public.profiles;

-- Create clean Profile Policies (No recursion)
CREATE POLICY "Users can insert their own profile" 
ON public.profiles FOR INSERT 
TO authenticated 
WITH CHECK (auth.uid() = id);

CREATE POLICY "Users can update their own profile" 
ON public.profiles FOR UPDATE 
TO authenticated 
USING (auth.uid() = id);

CREATE POLICY "Family members can view profiles" 
ON public.profiles FOR SELECT 
TO authenticated 
USING (
    -- User can view their own profile OR profiles belonging to the same family
    auth.uid() = id 
    OR 
    (family_id IS NOT NULL AND family_id = public.get_auth_family_id())
);


-- Drop all existing family policies
DROP POLICY IF EXISTS "Users can view their family" ON public.families;
DROP POLICY IF EXISTS "Authenticated users can insert families" ON public.families;
DROP POLICY IF EXISTS "Authenticated users can view families" ON public.families;

