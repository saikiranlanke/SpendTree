ON public.families FOR INSERT 
TO authenticated 
WITH CHECK (true);

CREATE POLICY "Authenticated users can view families" 
ON public.families FOR SELECT 
TO authenticated 
USING (
    id = public.get_auth_family_id() OR true -- Allows lookup by invite_code during signup
);


